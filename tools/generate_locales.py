"""Validate the two UI locales and emit a deterministic, compile-time C table."""
import json
from pathlib import Path
import re
import sys


KEY = re.compile(r"[a-z][a-z0-9]*(?:[._][a-z][a-z0-9]*)+\Z")
FORMAT = re.compile(r"%[-+ #0]*([0-9]+|\*)?(?:\.([0-9]*|\*))?(hh|ll|[hljztL])?([diuoxXfFeEgGaAcsp])")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate key: " + key)
        result[key] = value
    return result


def printf_args(text):
    """Argument order/types must match; positional formats and %n are forbidden."""
    args = []
    offset = 0
    while True:
        offset = text.find("%", offset)
        if offset < 0:
            return args
        if text.startswith("%%", offset):
            offset += 2
            continue
        match = FORMAT.match(text, offset)
        if not match:
            raise ValueError("invalid/unsupported printf placeholder at " + text[offset:])
        width, precision, length, conversion = match.groups()
        length = length or ""
        allowed = ("", "hh", "h", "l", "ll", "j", "z", "t") if conversion in "diuoxX" else (
            ("", "l", "L") if conversion in "fFeEgGaA" else ("",))
        if length not in allowed:
            raise ValueError("unsupported printf length: " + match.group())
        args.extend("int" for field in (width, precision) if field == "*")
        kind = "d" if conversion in "di" else "u" if conversion in "uoxX" else (
            "f" if conversion in "fFeEgGaA" else conversion)
        args.append((length, kind))
        offset = match.end()


def load_locale(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(data, dict) or not data:
        raise ValueError(str(path) + ": expected a nonempty flat JSON object")
    for key, value in data.items():
        if not KEY.fullmatch(key):
            raise ValueError(str(path) + ": invalid semantic key: " + key)
        if not isinstance(value, str) or not value or any(ord(c) < 32 and c != "\n" for c in value):
            raise ValueError(str(path) + ": expected nonempty text without control characters: " + key)
        value.encode("utf-8")  # Reject unpaired JSON surrogate escapes.
        try:
            printf_args(value)
        except ValueError as error:
            raise ValueError(str(path) + ": " + key + ": " + str(error)) from error
    return data


def identifier(key):
    return "UI_" + key.upper().replace(".", "_")


def c_string(value):
    # Fixed-width octal escapes preserve exact UTF-8 bytes, including accents;
    # they cannot swallow a following hex digit or form C trigraphs.
    return '"' + "".join(chr(b) if 32 <= b < 127 and b not in (34, 63, 92)
                         else "\\%03o" % b for b in value.encode("utf-8")) + '"'


def generate(english, portuguese):
    en, pt = load_locale(english), load_locale(portuguese)
    if en.keys() != pt.keys():
        raise ValueError("translation keys differ: missing=" + repr(sorted(en.keys() - pt.keys()))
                         + ", extra=" + repr(sorted(pt.keys() - en.keys())))
    keys = sorted(en)
    names = [identifier(key) for key in keys]
    if len(set(names)) != len(names) or "UI_NONE" in names:
        raise ValueError("semantic keys collide as C identifiers")
    for key in keys:
        if printf_args(en[key]) != printf_args(pt[key]):
            raise ValueError("incompatible printf placeholders: " + key)
    lines = ["// Generated by tools/generate_locales.py; edit locales/*.json instead.",
             "#ifndef METRO_UI_STRINGS_H", "#define METRO_UI_STRINGS_H", "",
             "typedef enum {", "  UI_NONE = 0,"]
    lines += ["  " + name + "," for name in names]
    lines += ["} UiKey;", ""]
    for name, data in (("en", en), ("pt_pt", pt)):
        lines += ["static const char *const s_ui_" + name + "[] = {", '  [UI_NONE] = "",']
        lines += ["  [" + identifier(key) + "] = " + c_string(data[key]) + "," for key in keys]
        lines += ["};", ""]
    return "\n".join(lines + ["#endif", ""])


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit("usage: generate_locales.py locales/en.json locales/pt-PT.json OUTPUT")
    try:
        output = generate(sys.argv[1], sys.argv[2])
        Path(sys.argv[3]).write_text(output, encoding="utf-8")
    except (ValueError, OSError) as error:
        sys.exit("locales: " + str(error))
