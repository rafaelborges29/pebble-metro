"""Validate the locale registry and emit keys, constant tables and mappings."""
import json
from pathlib import Path
import re
import sys


KEY = re.compile(r"[a-z][a-z0-9]*(?:[._][a-z][a-z0-9]*)+\Z")
FORMAT = re.compile(r"%[-+ #0]*([0-9]+|\*)?(?:\.([0-9]*|\*))?(hh|ll|[hljztL])?([diuoxXfFeEgGaAcsp])")


def unique_object(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError("duplicate key: " + key)
        result[key] = value
    return result


def printf_args(text):
    """Argument order/types must match; positional formats and %n are forbidden."""
    args = []
    offset = 0
    while True:
        offset = text.find("%", offset)
        if offset < 0:
            return args
        if text.startswith("%%", offset):
            offset += 2
            continue
        match = FORMAT.match(text, offset)
        if not match:
            raise ValueError("invalid/unsupported printf placeholder at " + text[offset:])
        width, precision, length, conversion = match.groups()
        length = length or ""
        allowed = ("", "hh", "h", "l", "ll", "j", "z", "t") if conversion in "diuoxX" else (
            ("", "l", "L") if conversion in "fFeEgGaA" else ("",))
        if length not in allowed:
            raise ValueError("unsupported printf length: " + match.group())
        args.extend("int" for field in (width, precision) if field == "*")
        kind = "d" if conversion in "di" else "u" if conversion in "uoxX" else (
            "f" if conversion in "fFeEgGaA" else conversion)
        args.append((length, kind))
        offset = match.end()


def load_locale(path):
    data = json.loads(Path(path).read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(data, dict) or not data:
        raise ValueError(str(path) + ": expected a nonempty flat JSON object")
    for key, value in data.items():
        if not KEY.fullmatch(key):
            raise ValueError(str(path) + ": invalid semantic key: " + key)
        if not isinstance(value, str) or not value or any(ord(c) < 32 and c != "\n" for c in value):
            raise ValueError(str(path) + ": expected nonempty text without control characters: " + key)
        value.encode("utf-8")  # Reject unpaired JSON surrogate escapes.
        try:
            printf_args(value)
        except ValueError as error:
            raise ValueError(str(path) + ": " + key + ": " + str(error)) from error
    return data


def identifier(key):
    return "UI_" + key.upper().replace(".", "_")


def c_string(value):
    # Fixed-width octal escapes preserve exact UTF-8 bytes, including accents;
    # they cannot swallow a following hex digit or form C trigraphs.
    return '"' + "".join(chr(b) if 32 <= b < 127 and b not in (34, 63, 92)
                         else "\\%03o" % b for b in value.encode("utf-8")) + '"'


def generate(registry):
    registry = Path(registry)
    config = json.loads(registry.read_text(encoding="utf-8"), object_pairs_hook=unique_object)
    if not isinstance(config, dict) or config.keys() != {"fallback", "locales"}:
        raise ValueError("locale registry requires fallback and locales")
    mappings, fallback = config["locales"], config["fallback"]
    if not isinstance(mappings, dict) or not mappings or not isinstance(fallback, str) or fallback not in mappings:
        raise ValueError("fallback must name a registered locale")
    for locale, filename in mappings.items():
        if not re.fullmatch(r"[a-z]{2,3}(?:_[A-Z]{2})?", locale):
            raise ValueError("invalid Pebble locale: " + locale)
        if not isinstance(filename, str) or not re.fullmatch(r"[a-zA-Z0-9_-]+\.json", filename) or filename == registry.name:
            raise ValueError("locale must reference a translation JSON filename: " + locale)
    files = sorted(set(mappings.values()))
    translations = {name: load_locale(registry.parent / name) for name in files}
    default = translations[mappings[fallback]]
    keys = sorted(default)
    names = [identifier(key) for key in keys]
    if len(set(names)) != len(names) or {"UI_NONE", "UI_KEY_COUNT"}.intersection(names):
        raise ValueError("semantic keys collide as C identifiers")
    for filename, data in translations.items():
        if default.keys() != data.keys():
            raise ValueError(filename + ": translation keys differ: missing=" + repr(sorted(default.keys() - data.keys()))
                             + ", extra=" + repr(sorted(data.keys() - default.keys())))
        for key in keys:
            if printf_args(default[key]) != printf_args(data[key]):
                raise ValueError(filename + ": incompatible printf placeholders: " + key)
    lines = ["// Generated by tools/generate_locales.py; edit locales/*.json instead.",
             "#ifndef METRO_UI_KEYS_H", "#define METRO_UI_KEYS_H", "",
             "typedef enum {", "  UI_NONE = 0,"]
    lines += ["  " + name + "," for name in names]
    lines += ["  UI_KEY_COUNT", "} UiKey;", "", "#endif", ""]
    tables = ["// Generated; private to localization.c.", '#include "ui_keys.h"', ""]
    table_names = {filename: "s_ui_table_" + str(i) for i, filename in enumerate(files)}
    for filename, data in translations.items():
        tables += ["static const char *const " + table_names[filename] + "[UI_KEY_COUNT] = {", '  [UI_NONE] = "",']
        tables += ["  [" + identifier(key) + "] = " + c_string(data[key]) + "," for key in keys]
        tables += ["};", ""]
    tables += ["static const struct { const char *locale; const char *const *strings; } s_ui_locales[] = {"]
    tables += ["  { " + c_string(locale) + ", " + table_names[mappings[locale]] + " }," for locale in sorted(mappings)]
    tables += ["};", "static const char *const *const s_ui_fallback = " + table_names[mappings[fallback]] + ";", ""]
    return "\n".join(lines), "\n".join(tables)


if __name__ == "__main__":
    if len(sys.argv) != 4:
        sys.exit("usage: generate_locales.py locales/index.json KEYS_HEADER TABLES_HEADER")
    try:
        for path, output in zip(sys.argv[2:], generate(sys.argv[1])):
            Path(path).write_text(output, encoding="utf-8")
    except (ValueError, OSError) as error:
        sys.exit("locales: " + str(error))
